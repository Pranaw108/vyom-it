// Builds and deploys a private preview (no search indexing) to the signed-in Cloudflare account.
// Usage: node scripts/deploy-preview.mjs <siteUrl> [--no-r2]
//   --no-r2  deploys without image storage, for accounts where R2 is not enabled yet.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const siteUrl = process.argv[2];
if (!siteUrl?.startsWith('https://')) {
  console.error('Usage: node scripts/deploy-preview.mjs https://<worker>.<subdomain>.workers.dev [--no-r2]');
  process.exit(1);
}
const env = { ...process.env, SITE_URL: siteUrl, CONTENT_SOURCE: 'remote', PUBLIC_INDEXING: 'false' };
execSync('npm run build', { stdio: 'inherit', env });

// The deploy uses the config generated by the build; adjust it for this environment.
const configPath = 'dist/server/wrangler.json';
const config = JSON.parse(readFileSync(configPath, 'utf8'));
config.vars = { ...config.vars, SITE_URL: siteUrl };
if (process.argv.includes('--no-r2')) delete config.r2_buckets;
writeFileSync(configPath, JSON.stringify(config, null, 2));

execSync('npx wrangler deploy', { stdio: 'inherit', env });
